import type { BarStyle } from '../stores/player'

/**
 * 满高应用面（终端 / 文件管理）在桌面端让给播放条的高度（v4.6.9）。
 *
 * 播放条是浮层：桌面端经典条是居中悬浮卡片、极简形态是右下角黑胶，两者都盖在内容之上。
 * 布局层（App.vue 的 `playerSpace`）因此不再给这两类页面预留整块高度 —— 否则页面被整体顶起，
 * 底栏会离开窗口底边，看起来就像「底部信息上浮」。让位改由页面内部的滚动区自己承担：
 * 底栏钉在窗口底部，内容区在滚动区里留出播放条的高度，两边都不遮挡对方。
 *
 * 只作用于 `lg` 断点：窄屏经典条是铺满底部的 dock，那部分高度仍由 App.vue 统一预留。
 */
export function playerClearance(style: BarStyle): string {
  if (style !== 'classic') {
    // 极简形态只是右下角一个 64px 黑胶角标：整块让位只会在底部留一条没人用的空白带，
    // 让它像 FAB 一样浮在内容上即可（不预留）。
    return ''
  }
  // 112 ≈ 桌面经典条（101 高、距底 24）+ 底栏 24 之外，再多留一圈呼吸位；
  // 实测这个值让终端最后一行的底边落在播放条上方约 6px，既不重叠也不留空带
  return 'lg:pb-[112px]'
}
